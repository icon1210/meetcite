"""Export meeting minutes as TXT, DOCX or PDF (FR12).

PDF uses WeasyPrint (installed in the Docker image). On machines where WeasyPrint's
system libraries are missing - common on Windows - it falls back to fpdf2.
"""

import html
import io
from dataclasses import dataclass
from typing import Any

from app.models import Meeting

AI_NOTICE = "Summary, decisions and action items were generated by AI. Check key points against the transcript."


def fmt_time(seconds: float) -> str:
    s = int(seconds)
    return f"{s // 3600:02d}:{s % 3600 // 60:02d}:{s % 60:02d}"


@dataclass
class Minutes:
    title: str
    date: str
    duration: str
    fact_check: str
    sections: list[tuple[str, list[str]]]  # (heading, bullet items)
    transcript: list[tuple[str, str, str]]  # (time, speaker, text)

    @property
    def notice(self) -> str:
        return f"{AI_NOTICE} {self.fact_check}".strip()


_FLAGS = {"partial": " [only partly supported by the transcript]", "unsupported": " [NOT supported by the transcript]"}


def _flag(item: dict[str, Any] | Any) -> str:
    verdict = item.get("verdict") if isinstance(item, dict) else getattr(item, "verdict", None)
    return _FLAGS.get(verdict or "", "")


def build_minutes(meeting: Meeting) -> Minutes:
    s = meeting.summary

    def action_line(a: Any) -> str:
        bits = [a.task, f"Owner: {a.owner or 'NOT ASSIGNED'}", f"Deadline: {a.deadline or 'none stated'}"]
        if a.status == "done":
            bits.append("Done")
        return " | ".join(bits) + _flag(a)

    sections: list[tuple[str, list[str]]] = []
    if s and s.overview:
        sections.append(("Overview", [s.overview]))
    sections.append(("Key points", [p["text"] + _flag(p) for p in s.points] if s else []))
    for topic in s.topics if s else []:
        items = [topic["summary"] + _flag(topic)]
        items += [f"{p['speaker']}: {p['view']}{_flag(p)}" for p in topic.get("positions", [])]
        items += [p["text"] + _flag(p) for p in topic.get("points", [])]
        items.append(f"Outcome: {topic.get('outcome') or 'nothing concluded'}")
        sections.append((f"Topic: {topic['title']}", items))
    sections.append(("Decisions", [d.text + _flag(d) for d in meeting.decisions]))
    sections.append(("Action items", [action_line(a) for a in meeting.action_items]))
    sections.append(("Open questions", [q["text"] + _flag(q) for q in s.open_questions] if s else []))
    sections.append(("Risks and concerns", [r["text"] + _flag(r) for r in s.risks] if s else []))

    v = s.verification if s else {}
    fact_check = (
        f"Fact-check: {v.get('supported', 0)} points verified, {v.get('partial', 0)} partly supported, "
        f"{v.get('unsupported', 0)} not supported (flagged below)."
        if v
        else ""
    )
    return Minutes(
        title=meeting.title,
        date=meeting.created_at.strftime("%d %B %Y"),
        duration=fmt_time(meeting.duration_s or 0),
        fact_check=fact_check,
        sections=[(h, items or ["(none)"]) for h, items in sections],
        transcript=[
            (fmt_time(seg.start_s), seg.speaker.display_name if seg.speaker else "Unknown", seg.current_text)
            for seg in meeting.segments
        ],
    )


def _sections(m: Minutes) -> list[tuple[str, list[str]]]:
    return m.sections


def to_txt(m: Minutes) -> bytes:
    out = [m.title, "=" * len(m.title), f"Date: {m.date}    Duration: {m.duration}", "", m.notice, ""]
    for heading, items in _sections(m):
        out += [heading, "-" * len(heading), *[f"- {i}" for i in items], ""]
    out += ["Transcript", "-" * 10]
    out += [f"[{t}] {speaker}: {text}" for t, speaker, text in m.transcript]
    return "\n".join(out).encode("utf-8")


def to_docx(m: Minutes) -> bytes:
    from docx import Document
    from docx.shared import Pt, RGBColor

    doc = Document()
    doc.add_heading(m.title, level=0)
    doc.add_paragraph(f"Date: {m.date}    Duration: {m.duration}")
    notice = doc.add_paragraph().add_run(m.notice)
    notice.italic = True
    notice.font.size = Pt(9)
    for heading, items in _sections(m):
        doc.add_heading(heading, level=1)
        for item in items:
            doc.add_paragraph(item, style="List Bullet")
    doc.add_heading("Transcript", level=1)
    for t, speaker, text in m.transcript:
        p = doc.add_paragraph()
        stamp = p.add_run(f"[{t}] ")
        stamp.font.color.rgb = RGBColor(0x66, 0x66, 0x66)
        p.add_run(f"{speaker}: ").bold = True
        p.add_run(text)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _html(m: Minutes) -> str:
    e = html.escape
    parts = [
        "<html><head><meta charset='utf-8'><style>",
        "body{font-family:Helvetica,Arial,sans-serif;font-size:11pt;color:#111;margin:2cm}",
        "h1{color:#1f3a5f;margin-bottom:4px}h2{color:#1f3a5f;border-bottom:1px solid #ccd;padding-bottom:2px}",
        ".meta{color:#555}.notice{font-style:italic;font-size:9pt;color:#555}",
        ".t{color:#777;font-size:9pt}.s{font-weight:bold}p.line{margin:3px 0}",
        "</style></head><body>",
        f"<h1>{e(m.title)}</h1><p class='meta'>Date: {e(m.date)} &nbsp; Duration: {e(m.duration)}</p>",
        f"<p class='notice'>{e(m.notice)}</p>",
    ]
    for heading, items in _sections(m):
        parts.append(f"<h2>{e(heading)}</h2><ul>{''.join(f'<li>{e(i)}</li>' for i in items)}</ul>")
    parts.append("<h2>Transcript</h2>")
    parts += [
        f"<p class='line'><span class='t'>[{t}]</span> <span class='s'>{e(s)}:</span> {e(x)}</p>"
        for t, s, x in m.transcript
    ]
    parts.append("</body></html>")
    return "".join(parts)


def to_pdf(m: Minutes) -> bytes:
    try:
        from weasyprint import HTML

        return bytes(HTML(string=_html(m)).write_pdf())
    except (ImportError, OSError):
        return _pdf_fallback(m)


def _pdf_fallback(m: Minutes) -> bytes:
    from fpdf import FPDF

    def safe(text: str) -> str:  # the built-in PDF fonts only cover Latin-1
        return text.encode("latin-1", "replace").decode("latin-1")

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    def line(text: str, height: float) -> None:
        pdf.multi_cell(0, height, safe(text), new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "B", 18)
    line(m.title, 9)
    pdf.set_font("Helvetica", "", 10)
    line(f"Date: {m.date}    Duration: {m.duration}", 6)
    pdf.set_font("Helvetica", "I", 8)
    line(m.notice, 5)
    for heading, items in [*_sections(m), ("Transcript", [f"[{t}] {s}: {x}" for t, s, x in m.transcript])]:
        pdf.ln(3)
        pdf.set_font("Helvetica", "B", 13)
        line(heading, 8)
        pdf.set_font("Helvetica", "", 10)
        for item in items:
            line(("- " if heading != "Transcript" else "") + item, 5.5)
    return bytes(pdf.output())


EXPORTERS = {
    "txt": (to_txt, "text/plain; charset=utf-8"),
    "docx": (to_docx, "application/vnd.openxmlformats-officedocument.wordprocessingml.document"),
    "pdf": (to_pdf, "application/pdf"),
}
